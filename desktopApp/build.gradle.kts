import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    alias(libs.plugins.kotlinJvm)
    alias(libs.plugins.composeMultiplatform)
    alias(libs.plugins.composeCompiler)
}

// JDK 25 (LTS): needed for TLS keying material exporters (pairing codes), which JDK 21 lacks.
// Gradle downloads it automatically (foojay resolver in settings.gradle.kts).
kotlin {
    jvmToolchain(25)
}

dependencies {
    implementation(project(":shared"))

    implementation(compose.desktop.currentOs)
    implementation(libs.compose.foundation)
    implementation(libs.compose.material3)
    implementation(libs.kotlinx.coroutinesSwing)

    implementation(libs.ktor.serverNetty)
    implementation(libs.ktor.serverWebsockets)
    implementation(libs.jmdns)
    implementation(libs.bouncycastle.pkix)
    runtimeOnly(libs.slf4j.simple)

    testImplementation(libs.kotlin.test)
    testImplementation(libs.ktor.serverTestHost)
    testImplementation(libs.ktor.clientWebsockets)

    implementation(libs.compose.uiToolingPreview)
}

/** Development switch from gradle.properties; see the comment there. */
val allowPlaintext = providers.gradleProperty("linkdrop.allowPlaintext").map { it.toBoolean() }.orElse(false)

// Compiles the switch into the app as a constant, so a packaged app cannot be flipped at runtime.
val generateBuildFlags by tasks.registering {
    val allow = allowPlaintext
    val outDir = layout.buildDirectory.dir("generated/buildFlags/kotlin")
    inputs.property("allowPlaintext", allow)
    outputs.dir(outDir)
    doLast {
        val file = outDir.get().file("com/agnish/linkdrop/BuildFlags.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by desktopApp/build.gradle.kts from linkdrop.allowPlaintext. Do not edit.
            |package com.agnish.linkdrop
            |
            |object BuildFlags {
            |    const val ALLOW_PLAINTEXT: Boolean = ${allow.get()}
            |}
            |""".trimMargin(),
        )
    }
}
kotlin.sourceSets.main {
    kotlin.srcDir(generateBuildFlags)
    // The app icon, also used for the window at runtime. linkdrop.png is rendered from linkdrop.svg:
    //   rsvg-convert -w 512 -h 512 icons/linkdrop.svg -o icons/linkdrop.png
    resources.srcDir("icons")
}

// Release guard: packaging (.deb, distributables) is refused while plaintext is enabled.
val checkNoPlaintextInRelease by tasks.registering {
    val allow = allowPlaintext
    inputs.property("allowPlaintext", allow)
    doLast {
        if (allow.get()) {
            throw GradleException(
                "Packaging is blocked while linkdrop.allowPlaintext=true (gradle.properties). " +
                    "Releases require TLS + pairing; plaintext is for development only.",
            )
        }
    }
}
tasks.matching { it.name.startsWith("package") || it.name.endsWith("Distributable") }
    .configureEach { dependsOn(checkNoPlaintextInRelease) }

compose.desktop {
    application {
        mainClass = "com.agnish.linkdrop.MainKt"
        // Run and package with the JDK 25 toolchain above. Compose would otherwise use the JDK
        // running Gradle (21), which lacks the TLS exporter API the pairing code needs.
        javaHome = javaToolchains.launcherFor { languageVersion.set(JavaLanguageVersion.of(25)) }
            .get().metadata.installationPath.asFile.absolutePath
        // Netty loads its native transport with System.loadLibrary; JDK 25 warns about that (and
        // a later JDK will refuse it) unless native access is allowed. The app runs on the class
        // path, i.e. in the unnamed module.
        jvmArgs += "--enable-native-access=ALL-UNNAMED"

        nativeDistributions {
            // .deb for Debian/Ubuntu (needs dpkg-deb). Arch: packaging/arch/PKGBUILD, which
            // packages createDistributable's output instead.
            targetFormats(TargetFormat.Deb)
            packageName = "linkdrop"
            // Also the Arch package's pkgver (packaging/arch/PKGBUILD checks that they match).
            packageVersion = "1.0.0"
            linux {
                iconFile.set(project.file("icons/linkdrop.png"))
            }
        }
    }
}
